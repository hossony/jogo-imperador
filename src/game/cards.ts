export function crisisCard(stat: Stat, high: boolean): Card {
  const key = `${stat}_${high ? 'high' : 'low'}`;
  const [text, l, r, who] = CRISIS_TEXT[stat][high ? 'high' : 'low'];
  const [tl, tr] = CRISIS_TRAITS[key];
  return {
    id: `crise_${key}`,
    kind: 'crise',
    weight: 0,
    who,
    role: 'a queda',
    art: high ? 'crown' : 'chains',
    text,
    left: { label: l, effect: { fall: true, trait: tl, chronicle: `Caiu em desgraça: ${l.toLowerCase()}.` } },
    right: { label: r, effect: { fall: true, trait: tr, chronicle: `Caiu em desgraça: ${r.toLowerCase()}.` } },
  };
}

